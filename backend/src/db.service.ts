import { Injectable, OnModuleInit } from '@nestjs/common';
import { Pool } from 'pg';

export const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS tasks (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_text TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'running',
  summary TEXT,
  reason TEXT,
  product TEXT,
  model TEXT,
  effort TEXT,
  step_count INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS observations (
  id BIGSERIAL PRIMARY KEY,
  task_id INT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  step INT NOT NULL,
  url TEXT,
  title TEXT,
  page_text TEXT,
  elements JSONB,
  tabs JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS llm_calls (
  id BIGSERIAL PRIMARY KEY,
  task_id INT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  step INT NOT NULL,
  messages JSONB NOT NULL,
  response_content TEXT,
  tool_calls JSONB,
  usage JSONB,
  duration_ms INT,
  error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS actions (
  id BIGSERIAL PRIMARY KEY,
  task_id INT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  step INT NOT NULL,
  tool TEXT NOT NULL,
  args JSONB,
  ok BOOLEAN NOT NULL,
  detail TEXT,
  duration_ms INT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS user_answers (
  id BIGSERIAL PRIMARY KEY,
  task_id INT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  step INT NOT NULL,
  question TEXT NOT NULL,
  answer TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS task_messages (
  id BIGSERIAL PRIMARY KEY,
  task_id INT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  role TEXT NOT NULL,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS task_messages_task_idx ON task_messages(task_id, id);
`;

// idempotent additions for databases created before the feature landed
const MIGRATIONS = [
  `ALTER TABLE tasks ADD COLUMN IF NOT EXISTS skill TEXT`,
  `ALTER TABLE tasks ADD COLUMN IF NOT EXISTS attempts INT NOT NULL DEFAULT 0`,
  `ALTER TABLE tasks ADD COLUMN IF NOT EXISTS context TEXT`,
  `ALTER TABLE tasks ADD COLUMN IF NOT EXISTS steps JSONB`,
  `CREATE TABLE IF NOT EXISTS task_messages (
     id BIGSERIAL PRIMARY KEY,
     task_id INT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
     role TEXT NOT NULL,
     content TEXT NOT NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
  `CREATE INDEX IF NOT EXISTS task_messages_task_idx ON task_messages(task_id, id)`,
];

@Injectable()
export class DbService implements OnModuleInit {
  readonly pool: Pool;

  constructor() {
    this.pool = new Pool({
      host: process.env.PGHOST ?? '127.0.0.1',
      port: Number(process.env.PGPORT ?? 5432),
      user: process.env.PGUSER ?? 'root',
      password: process.env.PGPASSWORD ?? 'secret',
      database: process.env.PGDATABASE ?? 'web_robot',
      max: 5,
    });
  }

  async onModuleInit() {
    await this.ensureDatabase();
    await this.pool.query(SCHEMA_SQL);
    await this.migrateUuidTaskIds();
    for (const migration of MIGRATIONS) {
      await this.pool.query(migration);
    }
  }

  // one-time conversion for databases created before task ids became
  // sequential integers: rewrite uuid pk/fks in place, assigning integers in
  // created_at order so ids stay chronological and the sequence continues
  // past the highest assigned value
  private async migrateUuidTaskIds(): Promise<void> {
    const col = await this.pool.query(
      `SELECT data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'tasks' AND column_name = 'id'`,
    );
    if (col.rows[0]?.data_type !== 'uuid') return;
    console.log('[web-robot db] migrating task ids from uuid to sequential integers…');
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      await client.query(`ALTER TABLE tasks ADD COLUMN IF NOT EXISTS int_id INT`);
      await client.query(`
        WITH ordered AS (
          SELECT id AS old_id, row_number() OVER (ORDER BY created_at)::INT AS new_id FROM tasks
        )
        UPDATE tasks t SET int_id = o.new_id FROM ordered o WHERE t.id = o.old_id`);
      for (const table of ['observations', 'llm_calls', 'actions', 'user_answers']) {
        await client.query(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS int_task_id INT`);
        await client.query(`UPDATE ${table} c SET int_task_id = t.int_id FROM tasks t WHERE c.task_id = t.id`);
        await client.query(`ALTER TABLE ${table} DROP COLUMN task_id`);
        await client.query(`ALTER TABLE ${table} RENAME COLUMN int_task_id TO task_id`);
        await client.query(`ALTER TABLE ${table} ALTER COLUMN task_id SET NOT NULL`);
      }
      await client.query(`ALTER TABLE tasks DROP COLUMN id`);
      await client.query(`ALTER TABLE tasks RENAME COLUMN int_id TO id`);
      await client.query(`ALTER TABLE tasks ALTER COLUMN id SET NOT NULL`);
      await client.query(`ALTER TABLE tasks ADD PRIMARY KEY (id)`);
      await client.query(`ALTER TABLE tasks ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
      await client.query(
        `SELECT setval(pg_get_serial_sequence('tasks', 'id'), COALESCE((SELECT MAX(id) FROM tasks), 0) + 1, false)`,
      );
      for (const table of ['observations', 'llm_calls', 'actions', 'user_answers']) {
        await client.query(`ALTER TABLE ${table} ADD FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE`);
      }
      await client.query('COMMIT');
      console.log('[web-robot db] task ids are now sequential integers');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  }

  private async ensureDatabase() {
    const target = process.env.PGDATABASE ?? 'web_robot';
    const admin = new Pool({
      host: this.pool.options.host,
      port: this.pool.options.port,
      user: this.pool.options.user,
      password: this.pool.options.password,
      database: 'postgres',
      max: 1,
    });
    try {
      const exists = await admin.query('SELECT 1 FROM pg_database WHERE datname = $1', [target]);
      if (exists.rowCount === 0) {
        await admin.query(`CREATE DATABASE "${target.replace(/"/g, '')}"`);
      }
    } finally {
      await admin.end();
    }
  }
}
